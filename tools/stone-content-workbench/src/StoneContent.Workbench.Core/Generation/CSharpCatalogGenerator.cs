using System;
using System.Collections.Generic;
using System.Globalization;
using System.Text;
using StoneContent.Workbench.Core.Model;

namespace StoneContent.Workbench.Core.Generation
{
    /// <summary>One generated C# artifact: its file name and full text. Returned as data — the
    /// generator never writes to disk (CLI/web adapters own I/O).</summary>
    public sealed record GeneratedArtifact(string FileName, string Content);

    /// <summary>The result of a generation pass: the four ordered scratch artifacts.</summary>
    public sealed class GenerationResult
    {
        public GenerationResult(IReadOnlyList<GeneratedArtifact> artifacts)
        {
            Artifacts = artifacts;
        }

        public IReadOnlyList<GeneratedArtifact> Artifacts { get; }
    }

    /// <summary>Deterministic C# generator for the four data artifacts. It emits SELF-CONTAINED,
    /// data-only classes under the <c>StoneContent.Workbench.Generated</c> namespace — plain arrays of
    /// authored values, no hand-written types or algorithms — so the scratch output compiles standalone
    /// in the parity harness without pulling in the shipping Niflheim project.
    ///
    /// Determinism contract (Task 4): authored order preserved; LF newlines; a fixed auto-generated
    /// header carrying the source asset id + all four version pins; empty arrays emitted as
    /// <c>Array.Empty&lt;T&gt;()</c> (never untyped <c>new[] {}</c>). Generating twice yields byte-identical
    /// output. The generator NEVER writes to a production catalog path; that guard lives in the CLI.</summary>
    public sealed class CSharpCatalogGenerator
    {
        public const string GeneratedNamespace = "StoneContent.Workbench.Generated";

        public GenerationResult Generate(StoneContentDocument d)
        {
            if (d == null) throw new ArgumentNullException(nameof(d));
            return new GenerationResult(new List<GeneratedArtifact>
            {
                new GeneratedArtifact("HomesteadProgressionCatalog.Data.g.cs", GenerateNodes(d)),
                new GeneratedArtifact("FoundationalPieceCatalog.Data.g.cs", GenerateFoundational(d)),
                new GeneratedArtifact("StoneFacetPalette.Data.g.cs", GenerateFacets(d)),
                new GeneratedArtifact("TreeTuningCatalog.Data.g.cs", GenerateTuning(d)),
            });
        }

        private static string Header(StoneContentDocument d, string summary)
        {
            var sb = new StringBuilder();
            sb.Append("// <auto-generated>\n");
            sb.Append("// Generated by StoneContent.Workbench — DO NOT EDIT BY HAND.\n");
            sb.Append("// ").Append(summary).Append('\n');
            sb.Append("// source asset: ").Append(d.AssetId).Append('\n');
            sb.Append("// formatVersion: ").Append(Int(d.FormatVersion)).Append('\n');
            sb.Append("// pins: contentRegistry=").Append(Int(d.Versions.ContentRegistry))
              .Append(", foundationalCatalog=").Append(Int(d.Versions.FoundationalCatalog))
              .Append(", facetPalette=").Append(Int(d.Versions.FacetPalette))
              .Append(", treeTuning=").Append(Int(d.Versions.TreeTuning)).Append('\n');
            sb.Append("// </auto-generated>\n");
            return sb.ToString();
        }

        private static string GenerateNodes(StoneContentDocument d)
        {
            var sb = new StringBuilder();
            sb.Append(Header(d, "Homestead progression node roster (data only)."));
            sb.Append("using System;\n\n");
            sb.Append("namespace ").Append(GeneratedNamespace).Append("\n{\n");
            sb.Append("    public sealed record GeneratedPricing(int? DevelopmentBp, int? PurchaseAp);\n\n");
            sb.Append("    public sealed record GeneratedRequirements(\n");
            sb.Append("        bool RequiresCommittedTree,\n");
            sb.Append("        bool RequiresCurrentContentVersion,\n");
            sb.Append("        int MinActiveStoneLevel,\n");
            sb.Append("        int MinTreeLevel,\n");
            sb.Append("        bool RequiresActiveAttunement,\n");
            sb.Append("        bool RequiresOfferedStatus,\n");
            sb.Append("        bool RequiresDevelopmentAuthority,\n");
            sb.Append("        bool RequiresResponsibilityRange,\n");
            sb.Append("        string[] PriorOfferedNodeIds);\n\n");
            sb.Append("    public sealed record GeneratedNode(\n");
            sb.Append("        string Id,\n");
            sb.Append("        int Version,\n");
            sb.Append("        string TreeId,\n");
            sb.Append("        int TreeLevel,\n");
            sb.Append("        string DisplayLabel,\n");
            sb.Append("        string OutcomeType,\n");
            sb.Append("        string Ownership,\n");
            sb.Append("        string FirstBuildStatus,\n");
            sb.Append("        GeneratedPricing Pricing,\n");
            sb.Append("        GeneratedRequirements Requirements);\n\n");
            sb.Append("    public static class GeneratedHomesteadProgressionCatalog\n    {\n");
            sb.Append("        public const int ContentRegistryVersion = ").Append(Int(d.Versions.ContentRegistry)).Append(";\n\n");
            sb.Append("        public static readonly GeneratedNode[] Nodes = new GeneratedNode[]\n        {\n");
            foreach (var n in d.Nodes)
            {
                sb.Append("            new GeneratedNode(");
                sb.Append(Str(n.Id)).Append(", ").Append(Int(n.Version)).Append(", ").Append(Str(n.TreeId)).Append(", ");
                sb.Append(Int(n.TreeLevel)).Append(", ").Append(Str(n.DisplayLabel)).Append(", ");
                sb.Append(Str(n.OutcomeType)).Append(", ").Append(Str(n.Ownership)).Append(", ").Append(Str(n.FirstBuildStatus)).Append(",\n");
                sb.Append("                new GeneratedPricing(").Append(NullableInt(n.Pricing.DevelopmentBp)).Append(", ")
                  .Append(NullableInt(n.Pricing.PurchaseAp)).Append("),\n");
                sb.Append("                new GeneratedRequirements(");
                var r = n.Requirements;
                sb.Append(Bool(r.RequiresCommittedTree)).Append(", ").Append(Bool(r.RequiresCurrentContentVersion)).Append(", ");
                sb.Append(Int(r.MinActiveStoneLevel)).Append(", ").Append(Int(r.MinTreeLevel)).Append(", ");
                sb.Append(Bool(r.RequiresActiveAttunement)).Append(", ").Append(Bool(r.RequiresOfferedStatus)).Append(", ");
                sb.Append(Bool(r.RequiresDevelopmentAuthority)).Append(", ").Append(Bool(r.RequiresResponsibilityRange)).Append(", ");
                sb.Append(StringArray(r.PriorOfferedNodeIds)).Append(")),\n");
            }
            sb.Append("        };\n    }\n}\n");
            return sb.ToString();
        }

        private static string GenerateFoundational(StoneContentDocument d)
        {
            var c = d.Foundational.Catalog;
            var sb = new StringBuilder();
            sb.Append(Header(d, "Foundational construction-piece catalog (data only)."));
            sb.Append("using System;\n\n");
            sb.Append("namespace ").Append(GeneratedNamespace).Append("\n{\n");
            sb.Append("    public static class GeneratedFoundationalPieceCatalog\n    {\n");
            sb.Append("        public const string CatalogId = ").Append(Str(c.Id)).Append(";\n");
            sb.Append("        public const int CatalogVersion = ").Append(Int(c.Version)).Append(";\n");
            sb.Append("        public const string CatalogVersionTag = ").Append(Str(c.VersionTag)).Append(";\n\n");
            sb.Append("        public static readonly string[] Members = ").Append(StringArray(c.Members)).Append(";\n\n");
            sb.Append("        public static readonly string[] Exclusions = ").Append(StringArray(c.Exclusions)).Append(";\n");
            sb.Append("    }\n}\n");
            return sb.ToString();
        }

        private static string GenerateFacets(StoneContentDocument d)
        {
            var sb = new StringBuilder();
            sb.Append(Header(d, "Stone Facet palette (data only)."));
            sb.Append("using System;\n\n");
            sb.Append("namespace ").Append(GeneratedNamespace).Append("\n{\n");
            sb.Append("    public sealed record GeneratedFacet(string Id, string Category, string[] CandidateTreeIds);\n\n");
            sb.Append("    public static class GeneratedStoneFacetPalette\n    {\n");
            sb.Append("        public const int PaletteVersion = ").Append(Int(d.Versions.FacetPalette)).Append(";\n\n");
            sb.Append("        public static readonly GeneratedFacet[] Facets = new GeneratedFacet[]\n        {\n");
            foreach (var f in d.Facets)
            {
                sb.Append("            new GeneratedFacet(").Append(Str(f.Id)).Append(", ").Append(Str(f.Category)).Append(", ")
                  .Append(StringArray(f.CandidateTreeIds)).Append("),\n");
            }
            sb.Append("        };\n    }\n}\n");
            return sb.ToString();
        }

        private static string GenerateTuning(StoneContentDocument d)
        {
            var sb = new StringBuilder();
            sb.Append(Header(d, "Tree tuning catalog (data only) — held-T012 reference in the POC."));
            sb.Append("using System;\n\n");
            sb.Append("namespace ").Append(GeneratedNamespace).Append("\n{\n");
            sb.Append("    public sealed record GeneratedTreeTuning(\n");
            sb.Append("        string TreeId, int InitialLevel, int UnlockCostStep, int[] CumulativeBpThresholds);\n\n");
            sb.Append("    public static class GeneratedTreeTuningCatalog\n    {\n");
            sb.Append("        public const int TuningVersion = ").Append(Int(d.Versions.TreeTuning)).Append(";\n\n");
            sb.Append("        public static readonly GeneratedTreeTuning[] Tunings = new GeneratedTreeTuning[]\n        {\n");
            foreach (var t in d.Trees)
            {
                sb.Append("            new GeneratedTreeTuning(").Append(Str(t.Id)).Append(", ")
                  .Append(Int(t.Tuning.InitialLevel)).Append(", ").Append(Int(t.Tuning.UnlockCostStep)).Append(", ")
                  .Append(IntArray(t.Tuning.CumulativeBpThresholds)).Append("),\n");
            }
            sb.Append("        };\n    }\n}\n");
            return sb.ToString();
        }

        // ── deterministic literal emitters ───────────────────────────────────────────────────────
        private static string Int(int v) => v.ToString(CultureInfo.InvariantCulture);
        private static string NullableInt(int? v) => v.HasValue ? v.Value.ToString(CultureInfo.InvariantCulture) : "null";
        private static string Bool(bool v) => v ? "true" : "false";

        private static string Str(string s)
        {
            var b = new StringBuilder(s.Length + 2);
            b.Append('"');
            foreach (var c in s)
            {
                switch (c)
                {
                    case '"': b.Append("\\\""); break;
                    case '\\': b.Append("\\\\"); break;
                    case '\n': b.Append("\\n"); break;
                    case '\r': b.Append("\\r"); break;
                    case '\t': b.Append("\\t"); break;
                    default: b.Append(c); break;
                }
            }
            b.Append('"');
            return b.ToString();
        }

        private static string StringArray(IReadOnlyList<string> values)
        {
            if (values.Count == 0) return "Array.Empty<string>()";
            var b = new StringBuilder("new string[] { ");
            for (int i = 0; i < values.Count; i++)
            {
                if (i > 0) b.Append(", ");
                b.Append(Str(values[i]));
            }
            b.Append(" }");
            return b.ToString();
        }

        private static string IntArray(IReadOnlyList<int> values)
        {
            if (values.Count == 0) return "Array.Empty<int>()";
            var b = new StringBuilder("new int[] { ");
            for (int i = 0; i < values.Count; i++)
            {
                if (i > 0) b.Append(", ");
                b.Append(Int(values[i]));
            }
            b.Append(" }");
            return b.ToString();
        }
    }
}
